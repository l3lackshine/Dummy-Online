'use strict';
const assert = require('assert');
const fs = require('fs'), os = require('os'), path = require('path');
const Wallet = require('./src/wallet');
const w = new Wallet({ initialBalance: 1000, file: '' });
const a = 'a'.repeat(32), b = 'b'.repeat(32);
assert.equal(w.ensure(a, 'A').balance, 1000);
assert.equal(w.ensure(b, 'B').balance, 1000);
assert.equal(w.reserve(a, 'g1:a', 400).ok, true);
assert.equal(w.balance(a), 600);
assert.equal(w.reserve(a, 'g1:a', 400).duplicate, true, 'duplicate reserve is idempotent');
assert.equal(w.reserve(a, 'g2:a', 700).ok, false, 'cannot reserve more than available balance');
const s = w.settleBatch('settle-1', [{ walletId: a, reservationId: 'g1:a', delta: -250, reason: 'loss' }, { walletId: b, reservationId: 'g1:b', delta: 250, reason: 'win' }]);
assert.equal(s.ok, false, 'settlement with missing reservation must be atomic');
assert.equal(w.balance(a), 600, 'failed batch must not partially mutate balances');
assert.equal(w.reserve(b, 'g1:b', 400).ok, true);
const paid = w.settleBatch('settle-1', [{ walletId: a, reservationId: 'g1:a', delta: -250 }, { walletId: b, reservationId: 'g1:b', delta: 250 }]);
assert.equal(paid.ok, true);
assert.equal(w.balance(a), 750);
assert.equal(w.balance(b), 1250);
assert.equal(w.settleBatch('settle-1', [{ walletId: a, reservationId: 'g1:a', delta: -250 }, { walletId: b, reservationId: 'g1:b', delta: 250 }]).duplicate, true, 'duplicate settlement cannot pay twice');
assert.equal(w.reserved(a), 0);
assert.equal(w.recent(a).some(x => x.type === 'settlement' && x.amount === -250), true);
assert.equal(w.reserve(a, 'orphan:a', 100).ok, true);
assert.equal(w.releaseOrphanedReservations('test restart recovery'), 1);
assert.equal(w.balance(a), 750, 'orphaned reservation is refunded after restart');
const purchase = w.spend(a, 'purchase-1', 200, 'shop item backs:midnight');
assert.equal(purchase.ok, true); assert.equal(w.balance(a), 550);
assert.equal(w.spend(a, 'purchase-1', 200, 'shop item backs:midnight').duplicate, true, 'purchase retries are idempotent');
assert.equal(w.spend(a, 'purchase-1', 1, 'shop item backs:other').ok, false, 'same transaction id cannot change amount or item');
assert.equal(w.spend(a, 'purchase-2', 1000, 'shop item backs:gold').ok, false, 'cannot spend more than available balance');
const beforeOwnedRetry = w.balance(a);
assert.equal(w.spend(a, 'purchase-3', 200, 'shop item backs:midnight').alreadyOwned, true, 'an already-owned skin cannot be charged twice with a new transaction');
assert.equal(w.balance(a), beforeOwnedRetry);
const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'dummy-wallet-')), file = path.join(dir, 'wallets.json');
const diskA = new Wallet({ initialBalance: 1000, file }), diskId = 'e'.repeat(32); diskA.ensure(diskId); diskA.reserve(diskId, 'restart-reserve', 300);
const diskB = new Wallet({ initialBalance: 1000, file }); assert.equal(diskB.balance(diskId), 700); assert.equal(diskB.releaseOrphanedReservations(), 1); assert.equal(diskB.balance(diskId), 1000); fs.rmSync(dir, { recursive: true, force: true });
console.log('wallet tests passed: reserve, insufficient funds, atomic settlement, idempotency, ledger, persistence/restart recovery');
